/* 出庭人员的人格卡，注入上下文 */
function castCard(){
  return Object.entries(CASE.cast)
    .filter(([k,v])=>v.persona)
    .map(([k,v])=>`${k}=${v.who}：${v.persona}｜说话方式：${v.voice}`)
    .join("\n");
}
